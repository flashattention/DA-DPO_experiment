#!/bin/bash

# 에러 발생 시 즉시 스크립트 중단 (안전장치)
set -e

# ==========================================
# 0. 필수 환경변수 체크 (OpenAI API Key)
# ==========================================
if [ -z "$OPENAI_API_KEY" ]; then
    echo "❌ [오류] OPENAI_API_KEY 환경변수가 설정되지 않았습니다."
    echo "💡 실행 전 터미널에 다음 명령어를 입력해주세요:"
    echo "export OPENAI_API_KEY=\"sk-여기에_실제_API_키_입력\""
    exit 1
fi

# ==========================================
# 1. 타임스탬프 기반 고유 실험 폴더 생성
# ==========================================
TIMESTAMP=$(date +"%Y%m%d_%H%M%S")
EXP_DIR="runs/exp_${TIMESTAMP}"

echo "=================================================="
echo "🚀 [STAGE 1] 새로운 Ablation 실험을 시작합니다!"
echo "📁 실험 보관소: ${EXP_DIR}"
echo "=================================================="

# 실험 폴더 생성
mkdir -p "${EXP_DIR}"

# ==========================================
# 2. 3가지 Ablation 조건 정의
# ==========================================
# "가중치_컬럼명 저장될_하위폴더명 W&B_그래프_이름"
CONFIGS=(
    "weight_dpo output_dpo_model DPO_Baseline_${TIMESTAMP}"
    "weight_da_dpo output_da_dpo_model DADPO_${TIMESTAMP}"
    "weight_hc_da_dpo output_hc_da_dpo_model HCDADPO_${TIMESTAMP}"
)

# ==========================================
# 3. 순차적 모델 학습 (3번 스크립트 반복 실행)
# ==========================================
for config in "${CONFIGS[@]}"; do
    read -r WEIGHT_COL SUB_DIR RUN_NAME <<< "$config"
    FINAL_OUTPUT_DIR="${EXP_DIR}/${SUB_DIR}"
    
    echo ""
    echo "--------------------------------------------------"
    echo "▶️ [학습 진행 중] 모델: ${RUN_NAME}"
    echo "   - 적용 가중치: ${WEIGHT_COL}"
    echo "   - 어댑터 저장: ${FINAL_OUTPUT_DIR}"
    echo "--------------------------------------------------"

    # 3번 파이썬 스크립트 실행
    python src/3_train.py \
        --weight_col "${WEIGHT_COL}" \
        --output_dir "${FINAL_OUTPUT_DIR}" \
        --run_name "${RUN_NAME}"
        
    echo "✅ ${RUN_NAME} 학습 종료! VRAM 회수를 위해 5초 대기합니다..."
    sleep 5 
done

echo "=================================================="
echo "🎯 [STAGE 2] 모든 모델 학습 완료. 즉시 평가(Evaluation)를 시작합니다!"
echo "=================================================="

# ==========================================
# 4. 통합 평가 진행 (4번 스크립트 실행)
# ==========================================
python src/4_evaluate.py \
    --exp_dir "${EXP_DIR}"

echo "=================================================="
echo "📊 [STAGE 3] 추론 완료. GPT-4o 채점 및 논문용 시각화를 시작합니다!"
echo "=================================================="

# ==========================================
# 🌟 5. 채점 및 시각화 (5번 스크립트 실행)
# ==========================================
python src/5_visualize.py \
    --exp_dir "${EXP_DIR}"

echo ""
echo "=================================================="
echo "🎉 [ALL DONE] 대성공! 학습-추론-채점-시각화 파이프라인이 무사히 종료되었습니다."
echo "📂 [최종 결과물 확인]: ${EXP_DIR}/figures/ "
echo "=================================================="